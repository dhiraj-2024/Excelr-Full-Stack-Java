public class Loops {
    public static void main(String[] argu) {
        System.out.println("hwllo boys");

        // for loop
        for (int i = 0; i <= 10; i++) {
            System.out.println(i);
        }

        // while loop
        int j = 50;
        while (j <= 100) {
            System.out.println(j);
            j++;
        }
        // do while loop
        int k = 0;
        do {
            System.out.println(k);
            k++;
        } while (k <= 10);
    }
}