
// 1) What is JavaScript?
// JavaScript is a scripting language used to make web pages interactive and dynamic.

// 2) Is JavaScript used to implement Form Validations?
// Yes, JavaScript is used to validate form inputs before submitting data.

// 3) What is the Extension for JavaScript files?
// .js

// 4) How to Execute JavaScript files?
// In browser using <script> tag OR using Node.js (node file.js)

// 5) Which tag is used to include JavaScript into HTML?
// <script>

// 6) Is JavaScript used to develop Dynamic web pages?
// Yes, it is used to create dynamic and interactive web pages.

// 7) Explain types of web applications.
// Static: Fixed content
// Dynamic: Changes based on user/data
// SPA: Single page apps (React)
// MPA: Multiple page apps

// 8) Difference: Static vs Dynamic
// Static: No interaction, fixed content
// Dynamic: Interactive, data changes

// 9) Programming vs Scripting Languages
// Programming: Compiled (Java, C++)
// Scripting: Interpreted (JavaScript, Python)

// 10) Is JavaScript execution synchronous?
// Yes, by default it is synchronous (line by line)

// 11) Is JavaScript Object Based Scripting Language?
// Yes, it supports objects but not classical inheritance

// 12) Predefined objects in JavaScript
// Array, Object, String, Number, Date, Math

// 13) How to manipulate DOM Elements?
// document.getElementById(), querySelector(), etc.

// Example:
// document.getElementById("demo").innerHTML = "Hello";

// 14) How to debug JavaScript application?
// Using browser DevTools (console, breakpoints)

// 15) How to get Current Date?
// new Date()

// 16) How to display Data on webpage?
// document.write() OR innerHTML

// Example:
// document.body.innerHTML = "Hello";

// 17) How to display data on browser console?
// console.log()

// 18) Display array as table in console
// console.table([1,2,3])

// 19) Is JavaScript secured?
// Yes, but depends on how it is used (browser sandbox security)

// 20) How to view Page Source?
// Right click → View Page Source

// 21) How to open Browser console?
// Press F12 OR Ctrl+Shift+I

// 22) Are semicolons mandatory?
// No, but recommended

// 23) Why comments in JavaScript?
// To explain code and improve readability

// 24) Types of comments?
// Two types: Single-line and Multi-line

// 25) Single line comment syntax
// // This is a comment

// 26) Multi line comment syntax
/* This is
   multi-line comment */

// 27) Is JavaScript Compiler Based?
// No (but modern engines use JIT internally)

// 28) Is JavaScript Interpreter Based?
// Yes, it is mainly interpreted language

